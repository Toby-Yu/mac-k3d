use std::path::{Path, PathBuf};
use std::process::Command;

use crate::error::{Error, Result};

/// Download Jenkins agent.jar from the controller. Returns whether the jar on
/// disk changed.
///
/// The download goes to a side file first: writing over the jar a running agent
/// JVM has open makes it fail later with `NoClassDefFoundError`.
pub fn download_agent_jar(controller_url: &str, dest: &Path) -> Result<bool> {
    if let Some(parent) = dest.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| Error::Config(format!("failed to create {}: {e}", parent.display())))?;
    }
    let url = format!(
        "{}/jnlpJars/agent.jar",
        controller_url.trim_end_matches('/')
    );
    println!("Downloading agent.jar from {url}");
    let part = dest.with_extension("jar.part");
    let status = Command::new("curl")
        .args(["-fsSL", "-o", &part.display().to_string(), &url])
        .status()
        .map_err(|e| Error::CommandFailed {
            cmd: format!("curl {url}"),
            source: e.into(),
        })?;
    if !status.success() {
        let _ = std::fs::remove_file(&part);
        return Err(Error::CommandFailed {
            cmd: format!("curl {url}"),
            source: anyhow::anyhow!("exit {:?}", status.code()),
        });
    }
    let changed = swap_in_if_different(&part, dest)?;
    if changed {
        println!("Updated {}", dest.display());
    } else {
        println!("agent.jar unchanged");
    }
    Ok(changed)
}

/// Rename `fresh` over `dest` unless the bytes already match. A rename gives
/// the new jar a new inode, so a JVM still reading the old one is unaffected.
fn swap_in_if_different(fresh: &Path, dest: &Path) -> Result<bool> {
    let new = std::fs::read(fresh)
        .map_err(|e| Error::Config(format!("failed to read {}: {e}", fresh.display())))?;
    if std::fs::read(dest).ok().as_deref() == Some(new.as_slice()) {
        let _ = std::fs::remove_file(fresh);
        return Ok(false);
    }
    std::fs::rename(fresh, dest).map_err(|e| {
        Error::Config(format!(
            "failed to move {} to {}: {e}",
            fresh.display(),
            dest.display()
        ))
    })?;
    Ok(true)
}

/// Write a launch script for the inbound agent (secret filled after registration).
/// Returns whether the file changed.
pub fn write_launch_script(
    script_path: &Path,
    controller_url: &str,
    agent_name: &str,
    agent_jar: &Path,
    secret_placeholder: &str,
) -> Result<bool> {
    write_launch_script_with_java(
        script_path,
        controller_url,
        agent_name,
        agent_jar,
        secret_placeholder,
        "java",
    )
}

pub fn write_launch_script_with_java(
    script_path: &Path,
    controller_url: &str,
    agent_name: &str,
    agent_jar: &Path,
    secret_placeholder: &str,
    java_bin: &str,
) -> Result<bool> {
    if let Some(parent) = script_path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| Error::Config(format!("failed to create {}: {e}", parent.display())))?;
    }
    let path = crate::prepare::path_env::agent_tool_path();
    let body = format!(
        r#"#!/usr/bin/env bash
set -euo pipefail
# Generated by mac-k3d — replace SECRET if registration was manual.
# LaunchAgents otherwise get PATH=/usr/bin:/bin and miss Docker/Harbor.
export PATH="{path}"
exec "{java}" -jar "{jar}" \
  -url "{url}" \
  -secret "{secret}" \
  -name "{name}" \
  -webSocket
"#,
        path = path,
        java = java_bin,
        jar = agent_jar.display(),
        url = controller_url.trim_end_matches('/'),
        secret = secret_placeholder,
        name = agent_name,
    );
    let changed = std::fs::read_to_string(script_path).ok().as_deref() != Some(body.as_str());
    if changed {
        std::fs::write(script_path, body).map_err(|e| {
            Error::Config(format!("failed to write {}: {e}", script_path.display()))
        })?;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = std::fs::metadata(script_path)
            .map_err(|e| Error::Config(e.to_string()))?
            .permissions();
        perms.set_mode(0o755);
        std::fs::set_permissions(script_path, perms).map_err(|e| Error::Config(e.to_string()))?;
    }
    Ok(changed)
}

/// Agent secret in an existing launch script, unless it is still the placeholder.
fn existing_secret(script_path: &Path) -> Option<String> {
    let text = std::fs::read_to_string(script_path).ok()?;
    text.lines()
        .find_map(|l| l.trim().strip_prefix("-secret \""))
        .and_then(|rest| rest.split('"').next())
        .filter(|s| !s.is_empty() && *s != "REPLACE_ME")
        .map(str::to_string)
}

/// Register node via Jenkins REST API when token is available.
///
/// Returns Ok(Some(secret)) when registration succeeded, Ok(None) when skipped
/// (no token) or when create succeeded but secret could not be parsed.
pub fn try_register_node(
    controller_url: &str,
    agent_name: &str,
    remote_fs: &Path,
    labels: &[String],
    api_user: Option<&str>,
    api_token: Option<&str>,
) -> Result<Option<String>> {
    let (Some(user), Some(token)) = (api_user, api_token) else {
        println!(
            "\nNo Jenkins API token provided — skipping auto-registration.\n\
             Create a Permanent Agent named '{agent_name}' on the controller, then run the launch script.\n\
             Labels: {}\n\
             Remote root: {}\n\
             Controller: {controller_url}\n",
            labels.join(" "),
            remote_fs.display()
        );
        return Ok(None);
    };

    let base = controller_url.trim_end_matches('/');
    let auth = format!("{user}:{token}");
    let labels_joined = labels.join(" ");

    let cookie_file = tempfile_path("mac-k3d-jenkins-cookies")?;
    let crumb = fetch_crumb(base, &auth, &cookie_file);

    // Skip create if node already exists.
    let exists = curl_status(
        base,
        &auth,
        &format!("/computer/{agent_name}/api/json"),
        &crumb,
        &cookie_file,
    )
    .map(|c| c == 200)
    .unwrap_or(false);

    let xml = agent_config_xml(agent_name, remote_fs, &labels_joined);
    if !exists {
        // Modern Jenkins: POST /computer/createItem?name=… with XML body.
        // (doCreateItem expects a Stapler form submission and returns HTTP 400 for raw XML.)
        let create_url = format!(
            "{base}/computer/createItem?name={}",
            urlencoding_simple(agent_name)
        );
        println!("Registering Jenkins agent '{agent_name}' on {base} …");
        let mut cmd = Command::new("curl");
        cmd.args([
            "-sS",
            "-b",
            &cookie_file.display().to_string(),
            "-c",
            &cookie_file.display().to_string(),
            "-u",
            &auth,
            "-H",
            "Content-Type: application/xml",
            "-X",
            "POST",
            &create_url,
            "--data-binary",
            &xml,
            "-w",
            "\n%{http_code}",
        ]);
        if let Some((field, value)) = &crumb {
            cmd.args(["-H", &format!("{field}: {value}")]);
        }
        let output = cmd.output().map_err(|e| Error::CommandFailed {
            cmd: "curl computer/createItem".into(),
            source: e.into(),
        })?;
        let raw = String::from_utf8_lossy(&output.stdout);
        let code = raw.lines().last().unwrap_or("").trim().to_string();
        if code != "200" && code != "201" && code != "302" && code != "303" {
            let body: String = raw
                .lines()
                .rev()
                .skip(1)
                .collect::<Vec<_>>()
                .into_iter()
                .rev()
                .collect::<Vec<_>>()
                .join("\n");
            let snippet: String = body.chars().take(240).collect();
            println!(
                "Warning: failed to create agent via API (HTTP {code}). {snippet}\n\
                 Create the node in the UI, then paste the secret into the launch script."
            );
            let _ = std::fs::remove_file(&cookie_file);
            return Ok(None);
        }
    } else {
        // Rewrite an existing node so executors and labels follow this config;
        // the JNLP secret is derived from the node name and survives.
        match post_node_config(base, &auth, agent_name, &xml, &crumb, &cookie_file) {
            Ok(code) if code == "200" || code == "204" => println!(
                "Jenkins agent '{agent_name}' already exists; updated it to {EXECUTORS} executor and labels '{labels_joined}'."
            ),
            Ok(code) => println!(
                "Warning: Jenkins agent '{agent_name}' exists but its config could not be updated (HTTP {code}). \
                 Set # of executors to {EXECUTORS} on {base}/computer/{agent_name}/configure."
            ),
            Err(err) => println!("Warning: could not update agent '{agent_name}' ({err})."),
        }
    }

    let secret = fetch_jnlp_secret(base, &auth, agent_name, &crumb, &cookie_file);
    let _ = std::fs::remove_file(&cookie_file);

    match secret {
        Some(secret) => {
            println!("Retrieved agent connection secret.");
            Ok(Some(secret))
        }
        None => {
            println!(
                "Agent created (or already present), but could not parse JNLP secret.\n\
                 Open {base}/computer/{agent_name}/ and copy the secret into the launch script."
            );
            Ok(None)
        }
    }
}

/// One eval build per worker. Each build locks every core of its worker and
/// Harbor fills them, so the queue hands the next shard to whichever worker
/// frees up first instead of piling shards onto one node.
const EXECUTORS: u32 = 1;

fn post_node_config(
    base: &str,
    auth: &str,
    agent_name: &str,
    xml: &str,
    crumb: &Option<(String, String)>,
    cookie_file: &Path,
) -> Result<String> {
    let mut cmd = Command::new("curl");
    cmd.args([
        "-sS",
        "-o",
        "/dev/null",
        "-b",
        &cookie_file.display().to_string(),
        "-c",
        &cookie_file.display().to_string(),
        "-u",
        auth,
        "-H",
        "Content-Type: application/xml",
        "-X",
        "POST",
        &format!("{base}/computer/{}/config.xml", urlencoding_simple(agent_name)),
        "--data-binary",
        xml,
        "-w",
        "%{http_code}",
    ]);
    if let Some((field, value)) = crumb {
        cmd.args(["-H", &format!("{field}: {value}")]);
    }
    let output = cmd.output().map_err(|e| Error::CommandFailed {
        cmd: "curl computer/config.xml".into(),
        source: e.into(),
    })?;
    Ok(String::from_utf8_lossy(&output.stdout).trim().to_string())
}

fn agent_config_xml(name: &str, remote_fs: &Path, labels: &str) -> String {
    let executors = EXECUTORS;
    format!(
        r#"<?xml version='1.1' encoding='UTF-8'?>
<slave>
  <name>{name}</name>
  <description>mac-k3d worker agent</description>
  <remoteFS>{remote}</remoteFS>
  <numExecutors>{executors}</numExecutors>
  <mode>NORMAL</mode>
  <retentionStrategy class="hudson.slaves.RetentionStrategy$Always"/>
  <launcher class="hudson.slaves.JNLPLauncher">
    <workDirSettings>
      <disabled>false</disabled>
      <internalDir>remoting</internalDir>
      <failIfWorkDirIsMissing>false</failIfWorkDirIsMissing>
    </workDirSettings>
    <webSocket>true</webSocket>
  </launcher>
  <label>{labels}</label>
  <nodeProperties/>
</slave>
"#,
        remote = remote_fs.display(),
    )
}

fn tempfile_path(prefix: &str) -> Result<PathBuf> {
    let dir = std::env::temp_dir();
    let path = dir.join(format!("{prefix}-{}", std::process::id()));
    // Ensure file exists for curl -c
    std::fs::File::create(&path).map_err(|e| Error::Config(e.to_string()))?;
    Ok(path)
}

fn fetch_crumb(base: &str, auth: &str, cookie_file: &Path) -> Option<(String, String)> {
    let output = Command::new("curl")
        .args([
            "-fsS",
            "-b",
            &cookie_file.display().to_string(),
            "-c",
            &cookie_file.display().to_string(),
            "-u",
            auth,
            &format!("{base}/crumbIssuer/api/json"),
        ])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let text = String::from_utf8_lossy(&output.stdout);
    let field = extract_json_str(&text, "crumbRequestField")?;
    let crumb = extract_json_str(&text, "crumb")?;
    Some((field, crumb))
}

fn curl_status(
    base: &str,
    auth: &str,
    path: &str,
    crumb: &Option<(String, String)>,
    cookie_file: &Path,
) -> Option<i32> {
    let mut args = vec![
        "-sS".into(),
        "-o".into(),
        "/dev/null".into(),
        "-w".into(),
        "%{http_code}".into(),
        "-b".into(),
        cookie_file.display().to_string(),
        "-c".into(),
        cookie_file.display().to_string(),
        "-u".into(),
        auth.to_string(),
        format!("{base}{path}"),
    ];
    if let Some((field, value)) = crumb {
        args.push("-H".into());
        args.push(format!("{field}: {value}"));
    }
    let output = Command::new("curl").args(&args).output().ok()?;
    String::from_utf8_lossy(&output.stdout).trim().parse().ok()
}

fn fetch_jnlp_secret(
    base: &str,
    auth: &str,
    agent_name: &str,
    crumb: &Option<(String, String)>,
    cookie_file: &Path,
) -> Option<String> {
    let mut cmd = Command::new("curl");
    cmd.args([
        "-fsS",
        "-b",
        &cookie_file.display().to_string(),
        "-c",
        &cookie_file.display().to_string(),
        "-u",
        auth,
        &format!("{base}/computer/{agent_name}/slave-agent.jnlp"),
    ]);
    if let Some((field, value)) = crumb {
        cmd.args(["-H", &format!("{field}: {value}")]);
    }
    let output = cmd.output().ok()?;
    if !output.status.success() {
        return None;
    }
    parse_jnlp_secret(&String::from_utf8_lossy(&output.stdout))
}

/// Parse inbound-agent secret from slave-agent.jnlp XML.
pub fn parse_jnlp_secret(text: &str) -> Option<String> {
    // Modern: <argument>SECRET</argument><argument>NAME</argument>…
    if let Some(idx) = text.find("<argument>") {
        let rest = &text[idx + "<argument>".len()..];
        let end = rest.find("</argument>")?;
        let first = rest[..end].trim();
        if !first.is_empty() && !first.starts_with('-') {
            return Some(first.to_string());
        }
    }
    // Legacy: <secret>HEX</secret>
    if let Some(idx) = text.find("<secret>") {
        let rest = &text[idx + "<secret>".len()..];
        let end = rest.find("</secret>")?;
        return Some(rest[..end].trim().to_string());
    }
    // Legacy: <argument>-secret</argument><argument>HEX</argument>
    if let Some(idx) = text.find("-secret</argument>") {
        let after = &text[idx + "-secret</argument>".len()..];
        let start = after.find("<argument>")? + "<argument>".len();
        let end = after[start..].find("</argument>")? + start;
        return Some(after[start..end].trim().to_string());
    }
    None
}

fn extract_json_str(json: &str, key: &str) -> Option<String> {
    let needle = format!("\"{key}\"");
    let idx = json.find(&needle)?;
    let after = &json[idx + needle.len()..];
    let colon = after.find(':')?;
    let rest = after[colon + 1..].trim_start();
    if !rest.starts_with('"') {
        return None;
    }
    let rest = &rest[1..];
    let end = rest.find('"')?;
    Some(rest[..end].to_string())
}

fn urlencoding_simple(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            'A'..='Z' | 'a'..='z' | '0'..='9' | '-' | '_' | '.' | '~' => c.to_string(),
            _ => format!("%{:02X}", c as u8),
        })
        .collect()
}

pub fn default_agent_name() -> String {
    let host = Command::new("hostname")
        .arg("-s")
        .output()
        .ok()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "mac".into());
    format!("mac-{host}")
}

pub fn default_remote_fs() -> PathBuf {
    std::env::var_os("HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("."))
        .join("jenkins-agent")
}

/// The Java the launch script runs: the recorded one when it runs, else what
/// discovery picks (a Java that meets JAVA_MAJOR first), else `java` on PATH.
pub fn agent_java(config: &crate::config::MacK3dConfig) -> String {
    config
        .dependencies
        .java
        .binary
        .as_ref()
        .filter(|p| p.exists())
        .map(|p| p.display().to_string())
        .filter(|s| {
            std::process::Command::new(s)
                .arg("-version")
                .output()
                .map(|o| o.status.success())
                .unwrap_or(false)
        })
        .or_else(|| {
            crate::prepare::discovery::best_java().map(|(bin, _)| bin.display().to_string())
        })
        .unwrap_or_else(|| "java".into())
}

/// Download jar, register node (if credentials present), write launch script.
pub fn ensure_worker_agent(config: &crate::config::MacK3dConfig) -> Result<()> {
    use crate::config::NodeRole;
    use crate::prepare::resources;

    if !matches!(config.role, NodeRole::Worker) {
        return Ok(());
    }
    let Some(url) = config.jenkins_agent.controller_url.clone() else {
        return Ok(());
    };
    let name = config
        .jenkins_agent
        .name
        .clone()
        .unwrap_or_else(default_agent_name);
    let jar = config.jenkins_agent.agent_jar.clone().unwrap_or_else(|| {
        config
            .storage
            .downloads_dir()
            .unwrap_or_else(|| PathBuf::from("downloads"))
            .join("jenkins-agent")
            .join("agent.jar")
    });
    let remote_fs = config
        .jenkins_agent
        .remote_fs
        .clone()
        .unwrap_or_else(default_remote_fs);

    // Controller may not be up yet during first prepare — do not abort the whole wizard.
    let mut jar_changed = false;
    let jar_ok = match download_agent_jar(&url, &jar) {
        Ok(changed) => {
            jar_changed = changed;
            true
        }
        Err(e) => {
            println!(
                "Note: could not download agent.jar from {url} ({e}).\n\
                 Jenkins controller is probably not running yet.\n\
                 Config will still be saved. After `mac-k3d start` / Jenkins is up, run:\n\
                   mac-k3d config -c <this-worker-config>"
            );
            false
        }
    };

    let secret = if jar_ok {
        try_register_node(
            &url,
            &name,
            &remote_fs,
            &config.jenkins_agent.labels,
            config.jenkins_agent.api_user(),
            config.jenkins_agent.api_token(),
        )?
    } else {
        None
    };
    let script = remote_fs.join("launch-agent.sh");
    // Without API credentials there is no new secret; keep the one already in use.
    let secret_placeholder = secret
        .or_else(|| existing_secret(&script))
        .unwrap_or_else(|| "REPLACE_ME".into());

    let java_bin = agent_java(config);

    let script_changed =
        write_launch_script_with_java(&script, &url, &name, &jar, &secret_placeholder, &java_bin)?;
    if script_changed {
        println!(
            "Wrote agent launch script: {} (java: {java_bin})",
            script.display()
        );
    } else {
        println!("Agent launch script unchanged: {}", script.display());
    }

    if jar_ok {
        resources::register_agent_cpu_cores(
            &url,
            &name,
            &config.resources.cpu_cores_label,
            config.jenkins_agent.cpu_cores,
            config.jenkins_agent.api_user(),
            config.jenkins_agent.api_token(),
        )?;
        crate::prepare::agent_service::install_and_start(
            &script,
            &remote_fs,
            jar_changed || script_changed,
        )?;
    } else {
        println!("Skipped agent daemon start until agent.jar is available from the controller.");
    }

    Ok(())
}

/// Stop LaunchAgent, then remove Jenkins node + CPU_CORES lockable resources.
pub fn remove_worker_agent(config: &crate::config::MacK3dConfig) -> Result<()> {
    use crate::config::NodeRole;
    use crate::prepare::resources;

    if !matches!(config.role, NodeRole::Worker) {
        return Ok(());
    }

    // Always stop local agent process first.
    let _ = crate::prepare::agent_service::stop_and_uninstall();

    let Some(url) = config.jenkins_agent.controller_url.as_deref() else {
        return Ok(());
    };
    let name = config
        .jenkins_agent
        .name
        .clone()
        .unwrap_or_else(default_agent_name);

    let user = config.jenkins_agent.api_user();
    let token = config.jenkins_agent.api_token();

    delete_node(url, &name, user, token)?;
    resources::remove_agent_cpu_cores(
        url,
        &name,
        &config.resources.cpu_cores_label,
        config.jenkins_agent.cpu_cores,
        user,
        token,
    )?;
    Ok(())
}

/// Stop only the local LaunchAgent (leave Jenkins node registered).
pub fn stop_worker_agent_process() -> Result<()> {
    crate::prepare::agent_service::stop_and_uninstall()
}

/// Delete a permanent agent via `POST /computer/{name}/doDelete`.
pub fn delete_node(
    controller_url: &str,
    agent_name: &str,
    api_user: Option<&str>,
    api_token: Option<&str>,
) -> Result<()> {
    let (Some(user), Some(token)) = (api_user, api_token) else {
        println!(
            "No Jenkins API token — skipping node delete for '{agent_name}'.\n\
             Remove it manually under Manage Jenkins → Nodes on {controller_url}."
        );
        return Ok(());
    };

    let base = controller_url.trim_end_matches('/');
    let auth = format!("{user}:{token}");
    let cookie_file = tempfile_path("mac-k3d-jenkins-delete")?;
    let crumb = fetch_crumb(base, &auth, &cookie_file);

    let exists = curl_status(
        base,
        &auth,
        &format!("/computer/{agent_name}/api/json"),
        &crumb,
        &cookie_file,
    )
    .map(|c| c == 200)
    .unwrap_or(false);

    if !exists {
        println!("Jenkins agent '{agent_name}' not present on {base}; nothing to delete.");
        let _ = std::fs::remove_file(&cookie_file);
        return Ok(());
    }

    println!("Deleting Jenkins agent '{agent_name}' on {base} …");
    let mut cmd = Command::new("curl");
    cmd.args([
        "-sS",
        "-o",
        "/dev/null",
        "-w",
        "%{http_code}",
        "-b",
        &cookie_file.display().to_string(),
        "-c",
        &cookie_file.display().to_string(),
        "-u",
        &auth,
        "-X",
        "POST",
        &format!("{base}/computer/{agent_name}/doDelete"),
    ]);
    if let Some((field, value)) = &crumb {
        cmd.args(["-H", &format!("{field}: {value}")]);
    }
    let output = cmd.output().map_err(|e| Error::CommandFailed {
        cmd: "curl computer/doDelete".into(),
        source: e.into(),
    })?;
    let _ = std::fs::remove_file(&cookie_file);
    let code = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if code == "200" || code == "302" || code == "303" {
        println!("Deleted Jenkins agent '{agent_name}'.");
    } else {
        println!(
            "Warning: failed to delete agent '{agent_name}' (HTTP {code}). Remove it in the Jenkins UI if it remains."
        );
    }
    Ok(())
}

